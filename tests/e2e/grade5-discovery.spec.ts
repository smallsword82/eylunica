import {test,expect} from './local-test';
import AxeBuilder from '@axe-core/playwright';
test('yedi ana ders, görselli matematik, animasyon kontrolü ve çevrimdışı keşif',async({page,context})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'eylunica’ya devam et →'}).click();
 await page.getByRole('button',{name:/5. Sınıf Derslerim/}).click();
 const shelf=page.getByRole('region',{name:'Yedi ana ders'});
 await expect(shelf.getByRole('button')).toHaveCount(7);
 await expect(page.getByRole('button',{name:/Bilişim|Görsel Sanatlar|Beden Eğitimi|Çoklu/})).toHaveCount(0);
 expect((await new AxeBuilder({page}).include('.discovery').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
 await shelf.getByRole('button',{name:/Matematik/}).click();
 const stored=await page.evaluate(()=>localStorage.getItem('eylunica-grade5-v1'));
 await expect(page.getByRole('heading',{name:/Bir rakamın/})).toBeVisible();
 await page.getByRole('button',{name:/Binler 4/}).click();
 await expect(page.getByText('= 4.000',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Hareketleri durdur'}).click();
 await expect(page.locator('.adventure-still')).toHaveCount(1);
 expect((await new AxeBuilder({page}).include('.math-adventure').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
 await page.screenshot({path:'.tools/math-pilot-mobile.png',fullPage:true});
 await page.getByRole('button',{name:/Rakamı taşımayı dene/}).click();
 await page.getByRole('button',{name:'5 rakamını binler kulesine taşı'}).click();
 await expect(page.getByRole('status')).toContainText('10 katına çıktı');
 await page.getByRole('button',{name:/Son göreve geç/}).click();
 await page.getByRole('button',{name:'80',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Bir ipucu daha');
 await page.getByRole('button',{name:'800',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Kapı açıldı');
 expect((await new AxeBuilder({page}).include('.math-adventure').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
 expect(await page.evaluate(()=>localStorage.getItem('eylunica-grade5-v1'))).toBe(stored);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await context.setOffline(true);
 await page.reload();
 await page.getByRole('button',{name:'eylunica’ya devam et →'}).click();
 await page.getByRole('button',{name:/5. Sınıf Derslerim/}).click();
 await shelf.getByRole('button',{name:/Matematik/}).click();
 expect(await page.locator('.adventure-hero').evaluate(async el=>{const match=getComputedStyle(el).backgroundImage.match(/url\("?([^"\)]+)/); if(!match)return false;const response=await fetch(match[1]);return response.ok;})).toBe(true);
 await page.getByRole('button',{name:/Matematik konuları ve yazılı testleri/}).click();
 await expect(page.getByRole('button',{name:'Yazılı testleri',exact:true})).toBeEnabled();
});
