"""Build-time only. See docs/SESLENDIRME.md for model/license and pinned tools.

Usage: python scripts/generate-narration.py --model-dir /path/to/vits-piper-tr_TR-fahrettin-medium
The model and Python dependencies are never shipped in the application.
"""
import argparse
import hashlib
import json
import pathlib
import subprocess
import tempfile
import re
import concurrent.futures
import av

import sherpa_onnx
import soundfile

parser = argparse.ArgumentParser()
parser.add_argument("--model-dir", required=True, type=pathlib.Path)
parser.add_argument("--ffmpeg", default="ffmpeg")
parser.add_argument("--workers", type=int, default=2)
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parent.parent
model = args.model_dir
texts = json.loads(subprocess.check_output([
    "node", "--experimental-strip-types", "--input-type=module", "-e",
    'import {stories} from "./src/reading-engine/index.ts"; '
    'import {narrationTexts,storyNarrationText} from "./src/audio/narration-texts.ts"; '
    'import {angleCoachTexts} from "./src/grade5/angle-coach.ts"; '
    'import {mathNarrationTexts} from "./src/grade5/math-narration.ts"; '
    'import {scienceNarrationTexts} from "./src/grade5/science-narration.ts"; '
    'console.log(JSON.stringify([...new Set([...Object.values(narrationTexts),...Object.values(angleCoachTexts),...mathNarrationTexts,...scienceNarrationTexts,...stories.map(s=>storyNarrationText(s.title,s.sentences))])]));',
], cwd=root, text=True))
config = sherpa_onnx.OfflineTtsConfig(
    model=sherpa_onnx.OfflineTtsModelConfig(
        vits=sherpa_onnx.OfflineTtsVitsModelConfig(
            model=str(model / "tr_TR-fahrettin-medium.onnx"),
            tokens=str(model / "tokens.txt"),
            data_dir=str(model / "espeak-ng-data"),
        ), num_threads=1, provider="cpu",
    ), max_num_sentences=1,
)
assert config.validate(), "Invalid TTS model configuration"
# Each worker owns its synthesizer; native inference releases the Python GIL.
import threading
worker_state = threading.local()
out = root / "public" / "narration"
out.mkdir(parents=True, exist_ok=True)
manifest = {}
def generate(text):
    with tempfile.TemporaryDirectory() as temp:
        wav = pathlib.Path(temp) / "narration.wav"
        digest = hashlib.sha256(text.encode()).hexdigest()[:16]
        filename = f"tr-{digest}.mp3"
        output = out / filename
        if not output.exists():
            if not hasattr(worker_state, 'tts'):
                worker_state.tts = sherpa_onnx.OfflineTts(config)
            spoken = re.sub(r'\?(?=\s*(?:=|[+−×÷]))', ' bilinmeyen ', text)
            spoken = spoken.replace('×',' çarpı ').replace('÷',' bölü ').replace('−',' eksi ').replace('+',' artı ').replace('=',' eşittir ').replace('°',' derece ').replace('cm²',' santimetrekare ').replace('cm',' santimetre ').replace('m²',' metrekare ').replace('□',' boş kutu ')
            audio = worker_state.tts.generate(spoken, sid=0, speed=0.94)
            soundfile.write(wav, audio.samples, audio.sample_rate)
            subprocess.run([
                args.ffmpeg, "-v", "error", "-y", "-i", str(wav),
                "-af", "loudnorm=I=-20:TP=-2:LRA=7,apad=whole_dur=1.1", "-ar", "24000",
                "-ac", "1", "-c:a", "libmp3lame", "-b:a", "56k", str(output),
            ], check=True)
        with av.open(str(output)) as container:
            duration = container.duration / av.time_base
        return text, {"file": filename, "duration": duration, "sha256": hashlib.sha256(output.read_bytes()).hexdigest()}
with concurrent.futures.ThreadPoolExecutor(max_workers=max(1,min(4,args.workers))) as pool:
    for i,(text,entry) in enumerate(pool.map(generate,texts)):
        manifest[text]=entry
        print(f"{i+1}/{len(texts)} {entry['file']}: {entry['duration']:.1f}s",flush=True)
(root / "src" / "audio" / "narration-manifest.ts").write_text(
    "// Generated by scripts/generate-narration.py; text keys prevent stale narration.\n"
    "export const narrationManifest: Record<string, {file: string; duration: number; sha256: string}> = "
    + json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n"
)
referenced = {entry["file"] for entry in manifest.values()}
for old in out.glob("tr-*.mp3"):
    if old.name not in referenced:
        old.unlink()
