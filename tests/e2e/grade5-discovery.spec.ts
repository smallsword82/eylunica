import {test,expect} from './local-test';
import AxeBuilder from '@axe-core/playwright';
test('kitaptan doğrudan konu haritası açılır; matematiğin bütün konuları görselli akıştadır',async({page,context})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:'eylunica’ya devam et →'}).click();
 await page.getByRole('button',{name:/5. Sınıf Derslerim/}).click();
 await expect(page.getByRole('region',{name:'Yedi ana ders'}).getByRole('button')).toHaveCount(7);
 await page.getByRole('button',{name:/^Matematik /}).click();
 await expect(page.getByRole('heading',{name:'Matematik keşif haritan'})).toBeVisible();
 await expect(page.locator('.math-topic-art')).toHaveCount(7);
 await expect(page.getByText('Kuleleri keşfet',{exact:true})).toHaveCount(0);
 await page.getByLabel('Çalışma dönemi').selectOption('all');
 const ids=await page.locator('[data-topic-id]').evaluateAll(nodes=>nodes.map(el=>el.getAttribute('data-topic-id')!));
 expect(ids).toHaveLength(20);
 const stored=await page.evaluate(()=>localStorage.getItem('eylunica-grade5-v1'));
 for(const id of ids){
  await page.locator(`[data-topic-id="${id}"]`).click();
  await expect(page.locator('.math-visual,.angle-lesson')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Konu alıştırmalarına geç →'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'← Konulara dön',exact:true}).click();
 }
 await page.locator('[data-topic-id="topic-a0155915387c7658"]').click();
 await page.getByRole('button',{name:'90°',exact:true}).click();
 await page.getByRole('button',{name:'Açımı kontrol et',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'90° ile görevi tamamladın'})).toBeVisible();
 await page.getByRole('button',{name:'Hareketleri durdur',exact:true}).click();
 await expect(page.locator('.angle-still')).toHaveCount(1);
 expect((await new AxeBuilder({page}).include('.angle-lesson').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
 await page.screenshot({path:'.tools/angle-integrated-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'← Konulara dön',exact:true}).click();
 await page.locator('[data-topic-id="topic-6a97ba45a911803c"]').click();
 expect((await new AxeBuilder({page}).include('.math-visual').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
 expect(await page.evaluate(()=>localStorage.getItem('eylunica-grade5-v1'))).toBe(stored);
 await page.getByRole('button',{name:'Konu alıştırmalarına geç →',exact:true}).click();
 await expect(page.getByRole('region',{name:'Soru çalışması'}).getByRole('heading')).toBeVisible();
 await page.evaluate(()=>navigator.serviceWorker.ready);await context.setOffline(true);await page.reload();
 await page.getByRole('button',{name:'eylunica’ya devam et →'}).click();
 await page.getByRole('button',{name:/5. Sınıf Derslerim/}).click();await page.getByRole('button',{name:/^Matematik /}).click();
 await page.locator('[data-topic-id="topic-a0155915387c7658"]').click();
 await expect(page.getByRole('region',{name:'Hareketli iletki'})).toBeVisible();
 expect(errors).toEqual([]);
});
