import { act, renderHook } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { Capacitor } from "@capacitor/core";
import { App as NativeApp } from "@capacitor/app";
import { useResponseClock } from "./useResponseClock";
vi.mock("@capacitor/app", () => ({ App: { addListener: vi.fn(), getState: vi.fn() } }));
afterEach(() => vi.restoreAllMocks());
it("mola dönüşü etkin süreyi korur, yeni soruda geçerli ölçümü yeniden başlatır", () => {
  let now = 0;
  vi.spyOn(performance, "now").mockImplementation(() => now);
  vi.spyOn(Capacitor, "isNativePlatform").mockReturnValue(false);
  vi.spyOn(document, "hasFocus").mockReturnValue(true);
  const h = renderHook(({ token, blocked }) => useResponseClock(token, blocked), { initialProps: { token: "a", blocked: false } });
  now = 2000;
  expect(h.result.current.read()).toEqual({ elapsedMs: 2000, timingValid: true });
  h.rerender({ token: "a", blocked: true });
  now = 62_000;
  h.rerender({ token: "a", blocked: false });
  now = 64_000;
  expect(h.result.current.read()).toEqual({ elapsedMs: 4000, timingValid: false });
  h.rerender({ token: "b", blocked: false });
  now = 67_000;
  expect(h.result.current.read()).toEqual({ elapsedMs: 3000, timingValid: true });
  act(() => window.dispatchEvent(new Event("blur")));
  now = 90_000;
  act(() => window.dispatchEvent(new Event("focus")));
  now = 91_000;
  expect(h.result.current.read()).toEqual({ elapsedMs: 4000, timingValid: false });
  h.unmount();
});
it("geciken Android durum sorgusu yeni arka plan sinyalini ezmez; dinleyici temizlenir", async () => {
  let now = 0, listener!: (s: { isActive: boolean }) => void;
  let resolve!: (s: { isActive: boolean }) => void;
  const remove = vi.fn();
  vi.spyOn(performance, "now").mockImplementation(() => now);
  vi.spyOn(Capacitor, "isNativePlatform").mockReturnValue(true);
  vi.mocked(NativeApp.addListener).mockResolvedValue({ remove });
  vi.mocked(NativeApp.getState).mockReturnValue(new Promise(r => { resolve = r; }));
  const h = renderHook(({ token }) => useResponseClock(token, false), { initialProps: { token: "a" } });
  await act(async () => {});
  listener = vi.mocked(NativeApp.addListener).mock.calls[0][1] as unknown as typeof listener;
  act(() => listener({ isActive: false }));
  await act(async () => resolve({ isActive: true }));
  now = 10_000;
  expect(h.result.current.read().elapsedMs).toBe(0);
  act(() => listener({ isActive: true }));
  h.rerender({ token: "b" });
  now = 11_000;
  expect(h.result.current.read()).toEqual({ elapsedMs: 1000, timingValid: true });
  h.unmount(); expect(remove).toHaveBeenCalledOnce();
});
